import { Schema } from 'effect'

/** Serializable example configuration; behavior is delivered through public Bindings. */
export const PreviewOptions = Schema.Struct({
  configuration: Schema.optionalKey(Schema.String),
  iconOnly: Schema.optionalKey(Schema.Boolean),
  expand: Schema.optionalKey(Schema.Literals(['one', 'oneOrNone', 'any'])),
  highlightExpanded: Schema.optionalKey(Schema.Boolean),
  multiple: Schema.optionalKey(Schema.Boolean),
  separated: Schema.optionalKey(Schema.Boolean),
  selected: Schema.optionalKey(Schema.Boolean),
  cardOrientation: Schema.optionalKey(Schema.Literals(['card', 'inline'])),
  calendarOrientation: Schema.optionalKey(Schema.Literals(['auto', 'horizontal', 'vertical'])),
  gaugeOrientation: Schema.optionalKey(Schema.Literals(['arc', 'linear'])),
  labelPlacement: Schema.optionalKey(Schema.Literals(['top', 'bottom', 'left', 'right'])),
  labelAlign: Schema.optionalKey(Schema.Literals(['start', 'center', 'end'])),
  edges: Schema.optionalKey(Schema.Literals(['curved', 'straight'])),
  labelLayout: Schema.optionalKey(Schema.Literals(['spread', 'grouped'])),
  color: Schema.optionalKey(
    Schema.Literals([
      'gray',
      'red',
      'orange',
      'amber',
      'yellow',
      'lime',
      'green',
      'emerald',
      'teal',
      'cyan',
      'blue',
      'indigo',
      'violet',
      'purple',
      'fuchsia',
      'pink',
      'rose',
    ]),
  ),
  label: Schema.optionalKey(Schema.String),
  placeholder: Schema.optionalKey(Schema.String),
  value: Schema.optionalKey(Schema.Union([Schema.String, Schema.Finite])),
  variant: Schema.optionalKey(Schema.String),
  size: Schema.optionalKey(Schema.Union([Schema.Literals(['default', 'compact']), Schema.Finite])),
  shape: Schema.optionalKey(Schema.Literals(['sharp', 'rounded', 'pill'])),
  hover: Schema.optionalKey(Schema.Literals(['fluid', 'standard'])),
  buttonSize: Schema.optionalKey(Schema.Literals(['default', 'compact', 'icon', 'icon-compact'])),
  disabled: Schema.optionalKey(Schema.Boolean),
  readOnly: Schema.optionalKey(Schema.Boolean),
  loading: Schema.optionalKey(Schema.Boolean),
  active: Schema.optionalKey(Schema.Boolean),
  checked: Schema.optionalKey(Schema.Boolean),
  leadingIcon: Schema.optionalKey(Schema.Boolean),
  trailingIcon: Schema.optionalKey(Schema.Boolean),
  type: Schema.optionalKey(Schema.String),
  orientation: Schema.optionalKey(Schema.Literals(['horizontal', 'vertical'])),
  highlight: Schema.optionalKey(Schema.Literals(['item', 'trigger'])),
  collapsible: Schema.optionalKey(Schema.Boolean),
  menuPresentation: Schema.optionalKey(Schema.Literals(['inline', 'popup'])),
  modalSize: Schema.optionalKey(Schema.Literals(['sm', 'lg', 'xl'])),
  position: Schema.optionalKey(Schema.Literals(['center', 'top'])),
  showCloseButton: Schema.optionalKey(Schema.Boolean),
  side: Schema.optionalKey(Schema.Literals(['top', 'right', 'bottom', 'left'])),
  align: Schema.optionalKey(Schema.Literals(['start', 'center', 'end', 'left', 'right'])),
  count: Schema.optionalKey(Schema.Int.check(Schema.isBetween({ minimum: 1, maximum: 12 }))),
  height: Schema.optionalKey(Schema.Int.check(Schema.isBetween({ minimum: 80, maximum: 600 }))),
  width: Schema.optionalKey(Schema.Int.check(Schema.isBetween({ minimum: 120, maximum: 800 }))),
  min: Schema.optionalKey(Schema.Finite),
  max: Schema.optionalKey(Schema.Finite),
  step: Schema.optionalKey(Schema.Finite),
  showValue: Schema.optionalKey(Schema.Boolean),
  showWeekNumber: Schema.optionalKey(Schema.Boolean),
  numberOfMonths: Schema.optionalKey(Schema.Literals([1, 2])),
  hideEyedropper: Schema.optionalKey(Schema.Boolean),
  clearable: Schema.optionalKey(Schema.Boolean),
  searchable: Schema.optionalKey(Schema.Boolean),
  loop: Schema.optionalKey(Schema.Boolean),
  autoplay: Schema.optionalKey(Schema.Boolean),
  strokeWidth: Schema.optionalKey(Schema.Finite),
  showGrid: Schema.optionalKey(Schema.Boolean),
  showAxis: Schema.optionalKey(Schema.Boolean),
  showTooltip: Schema.optionalKey(Schema.Boolean),
  showLabels: Schema.optionalKey(Schema.Boolean),
  aspectRatio: Schema.optionalKey(Schema.String),
  zoomEnabled: Schema.optionalKey(Schema.Boolean),
  scale: Schema.optionalKey(Schema.Finite),
  baseInnerRadius: Schema.optionalKey(Schema.Finite),
  ringGap: Schema.optionalKey(Schema.Finite),
  nodeWidth: Schema.optionalKey(Schema.Finite),
  nodePadding: Schema.optionalKey(Schema.Finite),
  levels: Schema.optionalKey(Schema.Finite),
  radius: Schema.optionalKey(Schema.Finite),
  barCount: Schema.optionalKey(Schema.Finite),
  showProgress: Schema.optionalKey(Schema.Boolean),
  showMarker: Schema.optionalKey(Schema.Boolean),
  showPercentage: Schema.optionalKey(Schema.Boolean),
  innerRadius: Schema.optionalKey(Schema.Finite),
  surface: Schema.optionalKey(Schema.Literals([1, 2, 3, 4, 5, 6, 7, 8])),
})
export type PreviewOptions = typeof PreviewOptions.Type
