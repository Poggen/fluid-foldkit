export function feedMedia(count: number) {
  return Array.from({ length: count }, (_, index) => {
    const photo = photoMedia[index % photoMedia.length] ?? photoMedia[0]
    if (photo === undefined) throw new Error('Photo assets are empty')
    return {
      ...photo,
      id: `feed-${index}`,
      alt: `Feed photo ${index + 1}`,
      caption: `Photo #${index + 1}`,
    }
  })
}
